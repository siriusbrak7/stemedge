function TranspirationStream() {
  const canvasRef = useRef<HTMLCanvasElement>(null);
  const animRef = useRef<number>(0);
  const timeRef = useRef(0);
  interface WaterParticle { x: number; y: number; speed: number; path: number }
  const particles = useRef<WaterParticle[]>([]);

  useEffect(() => {
    particles.current = [];
    for (let i = 0; i < 20; i++) {
      particles.current.push({ x: 0, y: 0, speed: 0.3 + Math.random() * 0.5, path: Math.random() });
    }
    const draw = () => {
      const canvas = canvasRef.current;
      if (!canvas) return;
      const ctx = canvas.getContext('2d');
      if (!ctx) return;
      timeRef.current += 0.016;
      const t = timeRef.current;
      const W = 300, H = 380;
      ctx.clearRect(0, 0, W, H);

      ctx.fillStyle = '#06090f';
      ctx.fillRect(0, 0, W, H);

      ctx.strokeStyle = 'rgba(34,211,238,0.15)';
      ctx.lineWidth = 3;
      ctx.beginPath();
      ctx.moveTo(150, 350);
      ctx.lineTo(150, 200);
      ctx.lineTo(150, 80);
      ctx.lineTo(120, 40);
      ctx.stroke();

      ctx.strokeStyle = 'rgba(34,211,238,0.1)';
      ctx.lineWidth = 8;
      ctx.beginPath();
      ctx.moveTo(150, 350);
      ctx.lineTo(150, 80);
      ctx.stroke();

      ctx.fillStyle = 'rgba(34,211,238,0.05)';
      for (let i = 0; i < 6; i++) {
        const angle = (i / 6) * Math.PI * 2;
        const cx = 150 + Math.cos(angle) * 15;
        const cy = 360 + Math.sin(angle) * 10;
        ctx.beginPath();
        ctx.moveTo(cx, cy);
        ctx.quadraticCurveTo(cx, cy - 40, 150, 330);
        ctx.stroke();
      }

      ctx.strokeStyle = 'rgba(34,211,238,0.3)';
      ctx.lineWidth = 1;
      ctx.beginPath();
      ctx.ellipse(150, 35, 40, 18, 0, 0, Math.PI * 2);
      ctx.stroke();
      ctx.beginPath();
      ctx.ellipse(150, 35, 55, 25, 0, 0, Math.PI * 2);
      ctx.stroke();

      for (let i = 0; i < 3; i++) {
        const yOff = -10 - i * 15;
        const xOff = 50 + i * 15;
        ctx.strokeStyle = 'rgba(34,211,238,0.15)';
        ctx.lineWidth = 0.8;
        ctx.beginPath();
        ctx.moveTo(150, 35);
        ctx.quadraticCurveTo(150 + xOff, 35 + yOff - 20, 150 + xOff + 20, 35 + yOff - 30);
        ctx.stroke();
      }

      particles.current.forEach(p => {
        const progress = ((t * p.speed * 0.3) % 1);
        const y = 360 - progress * 340;
        const x = 150 + Math.sin(y * 0.05 + p.path * 10) * 3;
        p.x = x; p.y = y;
        const alpha = Math.min(1, progress * 3) * Math.min(1, (1 - progress) * 3);
        ctx.beginPath();
        ctx.arc(x, y, 2.5, 0, Math.PI * 2);
        ctx.fillStyle = `rgba(34, 211, 238, ${alpha * 0.8})`;
        ctx.fill();
      });

      ctx.fillStyle = 'rgba(255,255,255,0.15)';
      ctx.font = '8px monospace';
      ctx.textAlign = 'center';
      ctx.fillText('ROOT', 150, 375);
      ctx.fillText('STEM (XYLEM)', 150, 190);
      ctx.fillText('LEAF', 150, 20);

      animRef.current = requestAnimationFrame(draw);
    };
    draw();
    return () => cancelAnimationFrame(animRef.current);
  }, []);

  return (
    <div className="flex flex-col gap-5 max-w-3xl mx-auto">
      <div className="flex justify-center">
        <div className="bg-black/60 rounded-2xl border border-brand-border p-2">
          <canvas ref={canvasRef} width={300} height={380} className="rounded-xl" />
        </div>
      </div>
      <div className="grid grid-cols-3 gap-3">
        {[
          { label: 'Root Uptake', desc: 'Root hairs absorb water by osmosis' },
          { label: 'Cohesion-Tension', desc: 'Water molecules pull each other upward' },
          { label: 'Transpiration Pull', desc: 'Evaporation from leaf creates suction' },
        ].map(item => (
          <div key={item.label} className="bg-slate-900/60 rounded-xl p-3 border border-slate-800">
            <div className="text-[10px] text-brand-accent font-bold uppercase tracking-widest mb-1">{item.label}</div>
            <div className="text-slate-400 text-xs">{item.desc}</div>
          </div>
        ))}
      </div>
    </div>
  );
}


function XylemPhloem() {
  const [revealed, setRevealed] = useState<Record<string, boolean>>({});
  const features = [
    { feature: 'Direction', xylem: 'Upward only (roots → leaves)', phloem: 'Both directions (source ↔ sink)' },
    { feature: 'Transports', xylem: 'Water + mineral ions', phloem: 'Sucrose + amino acids' },
    { feature: 'Cell type', xylem: 'Dead, hollow vessels', phloem: 'Living sieve tube elements + companion cells' },
    { feature: 'Strengthening', xylem: 'Lignin (waterproof & rigid)', phloem: 'No lignin (thin cellulose walls)' },
    { feature: 'End walls', xylem: 'Broken down (continuous tube)', phloem: 'Sieve plates with pores' },
    { feature: 'Mechanism', xylem: 'Cohesion-tension (passive)', phloem: 'Mass flow / active transport' },
    { feature: 'Position', xylem: 'Inner (closer to centre)', phloem: 'Outer (closer to epidermis)' },
    { feature: 'Cytoplasm', xylem: 'None (empty lumen)', phloem: 'Thin layer of cytoplasm' },
  ];
  return (
    <div className="flex flex-col gap-5 max-w-3xl mx-auto">
      <div className="bg-slate-900/60 rounded-2xl border border-brand-border overflow-hidden">
        <div className="grid grid-cols-3 gap-0 text-xs font-bold uppercase tracking-widest p-4 border-b border-slate-800">
          <div className="text-slate-500">Feature</div>
          <div className="text-center text-cyan-400">Xylem</div>
          <div className="text-center text-green-400">Phloem</div>
        </div>
        {features.map((row, i) => (
          <div key={row.feature} className="grid grid-cols-3 gap-0 p-4 text-sm border-b border-slate-800/50 cursor-pointer hover:bg-slate-800/20"
            onClick={() => setRevealed(prev => ({ ...prev, [row.feature]: !prev[row.feature] }))}
          >
            <div className="text-slate-400 font-medium text-xs">{row.feature}</div>
            <div className="text-center text-xs">
              {revealed[row.feature]
                ? <span className="text-cyan-300 font-mono">{row.xylem}</span>
                : <span className="text-slate-600">Click to reveal</span>}
            </div>
            <div className="text-center text-xs">
              {revealed[row.feature]
                ? <span className="text-green-300 font-mono">{row.phloem}</span>
                : <span className="text-slate-600">Click to reveal</span>}
            </div>
          </div>
        ))}
      </div>
      <button onClick={() => setRevealed(Object.fromEntries(features.map(f => [f.feature, true])))}
        className="px-4 py-2 bg-brand-accent text-black rounded-lg text-xs font-bold uppercase tracking-widest hover:bg-white transition-all self-center"
      >Reveal All</button>
    </div>
  );
}

